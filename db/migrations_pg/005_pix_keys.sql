-- Chaves Pix dos funcionarios por origem (Beta/Alfa), usadas pelo Agente DP ao responder
-- solicitacoes de Folha mensal, Ferias e Rescisao. Os dados sao carregados por scripts/import_pix.py
-- (nao ficam versionados no repo). name_key = nome sem acento, maiusculo, espacos colapsados.
CREATE TABLE IF NOT EXISTS pix_keys (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id INTEGER NOT NULL REFERENCES request_types(id),
  employee_name TEXT NOT NULL,
  name_key TEXT NOT NULL,
  pix_key TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"+00:00"'),
  updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"+00:00"'),
  UNIQUE (category_id, name_key)
);
CREATE INDEX IF NOT EXISTS idx_pix_keys_category ON pix_keys(category_id);

-- Historico de cadastro/alteracao de chave (quem, quando, valor antigo).
CREATE TABLE IF NOT EXISTS pix_key_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pix_key_id INTEGER NOT NULL REFERENCES pix_keys(id) ON DELETE CASCADE,
  old_key TEXT NOT NULL DEFAULT '',
  new_key TEXT NOT NULL DEFAULT '',
  changed_by_user_id INTEGER REFERENCES users(id),
  ticket_id INTEGER REFERENCES tickets(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"+00:00"')
);
CREATE INDEX IF NOT EXISTS idx_pix_key_history_key ON pix_key_history(pix_key_id, id DESC);
